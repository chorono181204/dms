import express from 'express';
import auth from '../../middlewares/auth';
import validate from '../../middlewares/validate';
import departmentValidation from '../../validations/department.validation';
import departmentController from '../../controllers/department.controller';

const router = express.Router();

router
    .route('/')
    .post(auth('manageUsers'), validate(departmentValidation.createDepartment), departmentController.createDepartment)
    .get(auth('getUsers'), validate(departmentValidation.getDepartments), departmentController.getDepartments);

router
    .route('/:departmentId')
    .get(auth('getUsers'), validate(departmentValidation.getDepartment), departmentController.getDepartment)
    .patch(auth('manageUsers'), validate(departmentValidation.updateDepartment), departmentController.updateDepartment)
    .delete(auth('manageUsers'), validate(departmentValidation.deleteDepartment), departmentController.deleteDepartment);

export default router;

